def test_windows_uses_redirected_known_folder_and_frees_result(monkeypatch, tmp_path):
    redirected = tmp_path / 'OneDrive' / '文档'
    redirected.mkdir(parents=True)
    value = ctypes.create_unicode_buffer(str(redirected))
    freed = []

    def known_folder(folder_id, flags, token, result):
        assert ctypes.string_at(folder_id, 16) == uuid.UUID('FDD39AD0-238F-46AF-ADB4-6C85480369C7').bytes_le
        assert flags == 0 and token is None
        result._obj.value = ctypes.addressof(value)
        return 0

    def free(pointer):
        freed.append(pointer.value)

    monkeypatch.setattr(user_folders.ctypes, 'windll', SimpleNamespace(
        shell32=SimpleNamespace(SHGetKnownFolderPath=known_folder),
        ole32=SimpleNamespace(CoTaskMemFree=free)), raising=False)
    monkeypatch.setattr(user_folders, 'sys', SimpleNamespace(platform='win32'))
    assert user_folders.documents_roots() == [str(redirected)]
    assert freed == [ctypes.addressof(value)]


@pytest.mark.parametrize('target', ['missing', 'home', 'root', 'failure'])
def test_windows_missing_or_broad_documents_never_falls_back(monkeypatch, tmp_path, target):
    monkeypatch.setattr(user_folders, 'sys', SimpleNamespace(platform='win32'))
    home = tmp_path / 'user'
    (home / 'Documents').mkdir(parents=True)
    monkeypatch.setattr(Path, 'home', lambda: home)

    def resolve_folder():
        if target == 'failure':
            raise OSError('Known folder lookup failed')
        return {'missing': str(home / 'gone'), 'home': str(home), 'root': home.anchor}[target]

    monkeypatch.setattr(user_folders, '_windows_documents', resolve_folder)
    assert user_folders.documents_roots() == []


